"""Ordinary CLI -> unchanged C17 and additive read-only native observations.

No compiler libraries, private records, proof gates, or producer fixtures used.
The retained oracle contains historical predictions; only its two normal cases
are read here. The source bytes and complete oracle are authenticated first.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess

from frozen import FROZEN, verify


def digest(data):
    return hashlib.sha256(data).hexdigest()


def insert_after(text, anchor, addition):
    if text.count(anchor) != 1:
        raise RuntimeError(f"Observer wiring requires exactly one {anchor!r}")
    return text.replace(anchor, anchor + "\n" + addition, 1)


def instrument(text, oracle):
    """Add statements only. All original generated bytes remain in order."""
    a, b = oracle["originals"]
    final_a, final_b = oracle["final"]

    def pair(stage, local, values):
        return (f'    r656_pair("{stage}", &nl_local_{local}.f0, '
                f'&nl_local_{local}.f1, {values[0]}, {values[1]});')

    text = '#include "observer.h"\n' + text
    text = insert_after(text, "    (void)nl_local_4;", "\n".join([
        "    const nl_type_10 *const r656_first = &nl_local_3;",
        "    const nl_type_10 *const r656_second = &nl_local_4;",
        "    r656_disjoint(r656_first, r656_second, sizeof(*r656_first));",
        pair("initial-first", 3, a), pair("initial-second", 4, b),
    ]))
    text = insert_after(text,
                        "    const uint8_t nl_local_6 = nl_if_result_28;", "\n".join([
        f'    r656_copy("condition", nl_local_5, {oracle["condition"]});',
        f'    r656_copy("selected", nl_local_6, {oracle["updates"][0]});',
    ]))
    text = insert_after(text,
                        "        const uint8_t nl_replace_old_33 = *nl_local_7;",
                        '        assert(nl_local_7 == &r656_first->f0);\n'
                        f'        r656_copy("first-read-old", nl_replace_old_33, {a[0]});')
    text = insert_after(text,
                        "    const uint8_t nl_local_8 = nl_loan_result_1;", "\n".join([
        f'    r656_copy("first-returned-old", nl_local_8, {oracle["old"][0]});',
        pair("after-first-first", 3, final_a),
        pair("after-first-second", 4, b),
    ]))
    text = insert_after(text,
                        "        const uint8_t nl_replace_old_54 = *nl_local_13;",
                        '\n'.join([
        '        assert(nl_local_13 == &r656_second->f0);',
        '        assert(nl_local_12 == nl_local_8);',
        f'        r656_copy("second-input", nl_local_12, {oracle["updates"][1]});',
        f'        r656_copy("second-read-old", nl_replace_old_54, {b[0]});',
    ]))
    text = insert_after(text,
                        "    const uint8_t nl_local_14 = nl_loan_result_2;", "\n".join([
        f'    r656_copy("second-returned-old", nl_local_14, {oracle["old"][1]});',
        '    assert(r656_first == &nl_local_3 && r656_second == &nl_local_4);',
        pair("final-first", 3, final_a), pair("final-second", 4, final_b),
    ]))
    return text


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("compiler", type=Path)
    parser.add_argument("cc")
    parser.add_argument("sanitizer", choices=["none", "address", "undefined"])
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    args.output.mkdir(parents=True, exist_ok=True)
    oracle = verify(root)  # Must precede every newlangc invocation.
    report = {"scope": "R656 NON-BLIND calibrated normal-native only",
              "cc": args.cc, "sanitizer": args.sanitizer, "commands": [], "cases": {}}
    report_path = args.output / "report.json"

    def run(command, label, silent=False):
        result = subprocess.run([str(x) for x in command], capture_output=True,
                                timeout=30, check=False)
        (args.output / f"{label}.stdout").write_bytes(result.stdout)
        (args.output / f"{label}.stderr").write_bytes(result.stderr)
        report["commands"].append({"label": label, "argv": [str(x) for x in command],
                                   "rc": result.returncode,
                                   "stdout_sha256": digest(result.stdout),
                                   "stderr_sha256": digest(result.stderr)})
        report_path.write_text(json.dumps(report, indent=2) + "\n")
        print(f"{label}: rc={result.returncode} stdout={len(result.stdout)} "
              f"stderr={len(result.stderr)}", flush=True)
        if result.returncode or (silent and result.stdout) or result.stderr:
            raise RuntimeError(f"STOP {label}: {shlex.join(map(str, command))}\n"
                               + result.stderr.decode(errors="replace"))
        return result.stdout

    run([args.cc, "--version"], "cc-version")
    for name, case in oracle["cases"].items():
        stem = Path(name).stem
        source = root / name
        run([args.compiler, "--check", source], f"{stem}-check", silent=True)
        emitted = run([args.compiler, source], f"{stem}-emit")
        if not emitted or run([args.compiler, source], f"{stem}-determinism") != emitted:
            raise RuntimeError("STOP: empty or nondeterministic C17")
        plain = args.output / f"{stem}.c17"
        plain.write_bytes(emitted)
        # The committed raw output is an independent byte reproducibility gate.
        retained = root / "generated" / plain.name
        if retained.exists() and retained.read_bytes() != emitted:
            raise RuntimeError(f"STOP: retained generated C17 drift: {name}")
        passive = args.output / f"{stem}.passive.c17"
        passive.write_text(instrument(emitted.decode(), case["oracle"]))
        report["cases"][name] = {"source_sha256": FROZEN[name][1],
                                  "generated_sha256": digest(emitted),
                                  "passive_sha256": digest(passive.read_bytes())}
        flags = ["-std=c17", "-pedantic-errors", "-Wall", "-Wextra", "-Werror"]
        if args.sanitizer != "none":
            flags += [f"-fsanitize={args.sanitizer}", "-fno-omit-frame-pointer",
                      "-fno-sanitize-recover=all"]
        for opt in ["O0", "O2"]:
            for mode, cfile in [("plain", plain), ("passive", passive)]:
                label = f"{stem}-{opt}-{mode}"
                exe = args.output / label
                run([args.cc, *flags, f"-{opt}", "-I", root, "-x", "c", cfile,
                     "-o", exe], label + "-build", silent=True)
                output = run([exe], label + "-run", silent=(mode == "plain"))
                if mode == "passive":
                    print(output.decode(), end="", flush=True)
                    if len(output.splitlines()) != 14:
                        raise RuntimeError("Observer observation count mismatch")
        report_path.write_text(json.dumps(report, indent=2) + "\n")
    report["result"] = "LIMITED NATIVE PASS"
    report_path.write_text(json.dumps(report, indent=2) + "\n")
    print("R656 TRUE+FALSE normal CLI strict C17/native LIMITED PASS", flush=True)


if __name__ == "__main__":
    os.environ.setdefault("ASAN_OPTIONS", "detect_leaks=1:halt_on_error=1")
    os.environ.setdefault("UBSAN_OPTIONS", "halt_on_error=1:print_stacktrace=1")
    main()
