"""R809: frozen independent calibrated source/contract checks, no guest fabrication."""
from pathlib import Path
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import base64

mode, compiler, known_probe, r_public, cc, sanitizer, location = sys.argv[1:]
base = Path(location)
frozen = json.loads((base / "freeze.json").read_text())
oracle = json.loads((base / "oracle.json").read_text())
positive = base / "sources" / "lexical_dual_copy.nl"
negative = [base / "sources" / name for name in oracle["negative"]]
for relative, digest in frozen["sha256"].items():
    p = base.parent.parent / relative
    actual = hashlib.sha256(p.read_bytes()).hexdigest()
    assert actual == digest, (p, actual, digest)
assert frozen["base"] == oracle["candidate"]

def invoke(args, env=None):
    return subprocess.run([str(a) for a in args], capture_output=True, env=env)

def ok(args, what, env=None):
    result = invoke(args, env)
    assert result.returncode == 0, (
        what, "return", result.returncode, "stdout", result.stdout.decode(errors="replace"),
        "stderr", result.stderr.decode(errors="replace"))
    return result

def checked():
    p = ok([compiler, "--check", positive], "real CHECK")
    assert not p.stdout and not p.stderr
    for n in negative:
        result = invoke([compiler, "--check", n])
        assert result.returncode != 0 and not result.stdout, (
            "negative admitted", n.name, result.returncode, result.stderr)
    print("R809_SOURCE authentic lexical LiveTail selected, six negatives refused", flush=True)

def public():
    checked()
    value = ok([known_probe, positive], "real source-issued CHECK probe").stdout.decode()
    records = [tuple(map(int, groups)) for groups in re.findall(
        r"COPY .*?index=(\d+).*?old=(\d+) new=(\d+) sibling=(\d+) body_status=(\d+) parameters_status=(\d+)", value)]
    expected = [(1, 172, 206, 41, 0, 0), (0, 94, 172, 63, 0, 0)]
    assert records == expected, (records, expected, value)
    assert "original_valid=1 local_view=1 local_valid=1 body_same_caller_world=1 entry_distinct_return=1" in value, value
    assert "same_ptr_root=1 same_allocation=1 same_domain=1" in value, value
    assert "post_proved=1 entry_original_exact=1" in value, value
    assert "NODE_BACKEND status=0" in value, value
    assert "SUMMARY Copy_calls=2 H_producers=1 owner_receivers=1 H_initializations=2" in value, value
    inits = re.findall(r"INITIALIZE .*root=(\d+) incarnation=(\d+) backing=(\d+) domain=(\d+)", value)
    assert len(inits) == 2 and all(a != b for a, b in zip(*inits)), inits
    # Intermediate arms are allowed to remain temporarily live; no all_closed=1 assertion.
    print("R809_PUBLIC Copy body+parameters old/new/sibling both fields, lexical H R/A/D OK", flush=True)
    print(value, flush=True)
    ok([r_public, positive], "R-owned alien-world/same-number/fact/loan rejection")
    print("R809_PUBLIC_NEGATIVE cross-world and false-currentness refused", flush=True)

def emit():
    content = ok([compiler, positive], "real emitted C17").stdout
    assert content and content.startswith(b"/* Bounded Checked-C")
    return content

def c17():
    checked()
    data = emit()
    with tempfile.TemporaryDirectory(prefix="r809-c17-") as td:
        path = Path(td) / "guest.c"
        path.write_bytes(data)
        named = Path(td) / "named.c"
        named.write_bytes(b"R809-C17-PRESERVE-BYTES")
        p = ok([compiler, "--emit-c17-to", named, positive], "real named C17")
        assert not p.stdout and not p.stderr and named.read_bytes() == data
        for neg in negative:
            named.write_bytes(b"R809-C17-PRESERVE-BYTES")
            p = invoke([compiler, "--emit-c17-to", named, neg])
            assert p.returncode != 0 and named.read_bytes() == b"R809-C17-PRESERVE-BYTES"
        for optimization in ("-O0", "-O2"):
            flags = ["-std=c17", "-pedantic-errors", "-Wall", "-Wextra", "-Werror", optimization]
            ok([cc, *flags, "-fsyntax-only", path], "strict C17 syntax " + optimization)
    print("R809_C17 literal generated bytes SHA256=" + hashlib.sha256(data).hexdigest(), flush=True)
    # R815 Gate A: immutable Actions log carries the ACTUAL compiler bytes, not example C.
    # Intentionally diagnostic RED; unrelated native/format errors remain visible.
    digest = hashlib.sha256(data).hexdigest()
    assert len(data) <= 300000, ("R815_GATE_A_CAPTURE_TOO_LARGE", len(data))
    print("R815_GATE_A_BEGIN sha256=" + digest + " bytes=" + str(len(data)), flush=True)
    encoded = base64.b64encode(data).decode("ascii")
    for offset in range(0, len(encoded), 96):
        print("R815_B64 " + encoded[offset:offset+96], flush=True)
    print("R815_GATE_A_END", flush=True)
    for lineno, line in enumerate(data.decode("utf-8").splitlines(), 1):
        if re.search(r"\\bNL_(?:HEAP|LIVE|MIXED)_[A-Z0-9_]+\\s*\\(", line):
            print("R815_HOOK_LINE %d %s" % (lineno, line.strip()), flush=True)
    print("R815_GATE_A_DIAGNOSTIC_RED_EVIDENCE_ONLY", flush=True)
    raise SystemExit(86)

def native():
    checked()
    emitted = emit()
    flags = ["-std=c17", "-pedantic-errors", "-Wall", "-Wextra", "-Werror"]
    if sanitizer != "none":
        flags += ["-fsanitize=" + sanitizer, "-fno-omit-frame-pointer", "-fno-sanitize-recover=all"]
    with tempfile.TemporaryDirectory(prefix="r809-native-") as td:
        tmp = Path(td)
        source = tmp / "guest.c"
        source.write_bytes(emitted)
        for opt in ("-O0", "-O2"):
            plain = tmp / ("plain" + opt[2:])
            ok([cc, *flags, opt, source, "-o", plain], "PLAIN unchanged C17 compile")
            normal = ok([plain], "PLAIN unchanged C17 runtime")
            # PLAIN exit0 does not prove malloc/free physical events or numeric T values.
            assert not normal.stdout and not normal.stderr, (normal.stdout, normal.stderr)
            print(json.dumps({"contract":"PLAIN_UNMODIFIED", "compiler":cc, "opt":opt,
                              "sanitizer":sanitizer, "exit":normal.returncode,
                              "physical_malloc_free":"NOT OBSERVABLE", "numeric_T":"NOT OBSERVABLE",
                              "C_sha256":hashlib.sha256(emitted).hexdigest()}), flush=True)
            seen = tmp / ("observed" + opt[2:])
            header = (base / "observer.h").resolve()
            wrapper = (base / "platform.c").resolve()
            defs = ['-DNEWLANG_HEAP_OBSERVER="' + str(header) + '"']
            obs_flags = ["-fno-builtin-malloc", "-fno-builtin-free"]
            ok([cc, *flags, opt, *obs_flags, *defs, source, wrapper,
                "-Wl,--wrap=malloc", "-Wl,--wrap=free", "-o", seen],
               "OBSERVATION-ONLY native build")
            for fail in ("0", "1", "2"):
                env = dict(os.environ, R809_FAIL=fail,
                           ASAN_OPTIONS="detect_leaks=1:halt_on_error=1",
                           UBSAN_OPTIONS="halt_on_error=1:print_stacktrace=1")
                run = ok([seen], "OBSERVED real malloc/free " + opt + " fail=" + fail, env)
                output = run.stdout.decode()
                expectations = {"0":(2,2,2), "1":(1,0,0), "2":(2,1,1)}
                req, alloc, freed = expectations[fail]
                assert ("requests=%s allocations=%s frees=%s" % (req, alloc, freed)) in output, output
                if fail == "0":
                    assert "T=41,206/172,63" in output, output
                    assert "COPY=2 lexical=1 received=1" in output, output
                else:
                    assert "COPY=0 lexical=0 received=0" in output, output
                print(json.dumps({"contract":"PASSIVE_WRAPPER_OBSERVER_ONLY",
                                  "compiler":cc, "opt":opt, "sanitizer":sanitizer,
                                  "fno_builtin_malloc_free":True,
                                  "fail_call":fail, "stdout":output.strip()}), flush=True)
    print("R809_NATIVE_FINITE_PASS all reached worlds (observer-only physical values)", flush=True)

if mode == "source":
    checked()
elif mode == "public":
    public()
elif mode == "c17":
    c17()
elif mode == "native":
    native()
else:
    raise SystemExit("R809 unknown test mode")
