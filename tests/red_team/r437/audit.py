#!/usr/bin/env python3
"""R437 one immutable native+public-evidence run. No P fixtures or logs consumed."""
import hashlib
import json
import os
import pathlib
import platform
import re
import shutil
import subprocess
import sys

ROOT=pathlib.Path(__file__).resolve().parents[3]
HERE=pathlib.Path(__file__).resolve().parent
OUT=HERE/"output"
OUT.mkdir(exist_ok=True)
BIN=ROOT/"build-r437"/"newlangc"
class Halt(Exception): pass
def digest(data): return hashlib.sha256(data).hexdigest()
def run(args, out=None, expect=0, env=None):
    p=subprocess.run(args,cwd=ROOT,stdout=subprocess.PIPE,stderr=subprocess.PIPE,env=env)
    tag=" ".join(map(str,args))
    print("COMMAND",tag, "EXIT",p.returncode,flush=True)
    if p.stderr:print("STDERR",p.stderr.decode(errors="replace")[:8000],flush=True)
    if p.stdout and out is None:print("STDOUT",p.stdout.decode(errors="replace")[:5000],flush=True)
    if out is not None:
        pathlib.Path(out).write_bytes(p.stdout)
        print("ARTIFACT",out,"BYTES",len(p.stdout),"SHA256",digest(p.stdout),flush=True)
    if expect is not None and p.returncode!=expect:raise Halt(f"unexpected exit {p.returncode} expected {expect}: {tag}")
    return p

print("R437 RUN HEADER",json.dumps({"host":platform.platform(),"sha":"d26d30568018f9d4866a9841d9eba6966a703557","branch":"r437-node-native-blind-ci","github_sha":os.getenv("GITHUB_SHA"),"run_id":os.getenv("GITHUB_RUN_ID"),"run_attempt":os.getenv("GITHUB_RUN_ATTEMPT")}),flush=True)
run(["git","rev-parse","HEAD"])
if run(["git","rev-parse","HEAD"]).stdout.decode().strip() != os.getenv("GITHUB_SHA"):raise Halt("actions checkout SHA drift")
if run(["git","merge-base","--is-ancestor","d26d30568018f9d4866a9841d9eba6966a703557","HEAD"]).returncode:raise Halt("candidate not ancestor")

# Source-level counterexamples are independent perturbations of R-owned inputs.
native_cases=[("none",HERE/"r_none.nl"),("some",HERE/"r_some.nl")]
negative=[]
for label,source in native_cases:
    text=source.read_text()
    print("SOURCE",label,"SHA256",digest(source.read_bytes()),flush=True)
    assert "payload: u8" in text and text.count("fn main") == 1
    p=run([str(BIN),"--check",str(source)],expect=0)
    if p.stdout or p.stderr:raise Halt("--check did not have silent successful output")
    c=OUT/(label+".c")
    run([str(BIN),str(source)],out=c,expect=0)
    if not c.read_bytes():raise Halt("empty C17")
    # Explicit public semantic artifact validator is linked against unchanged src/ libraries.
    run([str(OUT/"public_proof"),str(source)],expect=0)
    for cc,mode,flags in [
        ("gcc","o0",["-O0"]),("gcc","o2",["-O2"]),
        ("clang","o0",["-O0"]),("clang","o2",["-O2"]),
        ("clang","asan",["-O1","-fsanitize=address","-fno-omit-frame-pointer"]),
        ("clang","ubsan",["-O1","-fsanitize=undefined","-fno-sanitize-recover=all"])]:
        compiler=shutil.which(cc)
        if not compiler:print("UNAVAILABLE COMPILER",cc);raise Halt("compiler missing")
        exe=OUT/(label+"-"+cc+"-"+mode)
        args=[compiler,"-std=c17","-Wall","-Wextra","-Wpedantic","-Werror",*flags,str(c),"-o",str(exe)]
        run(args,expect=0)
        env=os.environ.copy()
        env["ASAN_OPTIONS"]="detect_leaks=1:halt_on_error=1"
        env["UBSAN_OPTIONS"]="halt_on_error=1:print_stacktrace=1"
        run([str(exe)],expect=0,env=env)
        print("NATIVE",label,cc,mode,"EXIT 0","BINARY_SHA256",digest(exe.read_bytes()),flush=True)

# Source-invalid cases: no manual registration/host-authority injection.
original=(HERE/"r_none.nl").read_text()
bad_field=original.replace("anchor@next","anchor@payload")
assert bad_field!=original
bad_escape=original.replace(
    "replace(out, Option<ptr<Node>>::Some(peer_ptr))",
    "out")
assert bad_escape!=original
for name,body in [("wrong_target_field",bad_field),("escaped_scoped_ref",bad_escape)]:
    src=OUT/(name+".nl")
    src.write_text(body)
    print("INVALID SOURCE",name,"SHA256",digest(src.read_bytes()),flush=True)
    p=run([str(BIN),"--check",str(src)],expect=None)
    print("NEGATIVE CLASSIFICATION",name,"source-rejection" if p.returncode==3 else "NONREJECTION_OR_OTHER",p.returncode,flush=True)
    if p.returncode != 3:raise Halt(f"expected source rejection: {name}")
    if p.stdout:raise Halt("rejected source emitted stdout")


# If C emitted source reveals an unambiguous Node record and both original
# C-locals, derive a purely read-only probe from R-generated C and execute it.
# The C17 source hash above is always from pristine, compiler-generated bytes;
# the separately hashed instrumented C is not claimed to be raw source output.
observation_ok=True
for label,source in native_cases:
    original_c=OUT/(label+".c")
    observer_c=OUT/(label+"-passive.c")
    obs=subprocess.run([sys.executable,str(HERE/"passive_observer.py"),str(original_c),str(observer_c),label],cwd=ROOT,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
    print("PASSIVE PLAN",label,obs.returncode,obs.stdout.decode(errors="replace"),obs.stderr.decode(errors="replace")[:1000],flush=True)
    if obs.returncode:
        observation_ok=False
        continue
    print("PASSIVE C17",label,"SHA256",digest(observer_c.read_bytes()),flush=True)
    if "tag=None" in obs.stdout.decode() or "ptr=None" in obs.stdout.decode():
        observation_ok=False
    for cc in ("gcc","clang"):
        for opt in ("-O0","-O2"):
            exe=OUT/(label+"-passive-"+cc+opt)
            run([cc,"-std=c17","-Wall","-Wextra","-Wpedantic","-Werror",opt,str(observer_c),"-o",str(exe)],expect=0)
            p=run([str(exe)],expect=0)
            if "R437_NATIVE_OBSERVER_OK" not in p.stderr.decode(errors="replace"):raise Halt("passive probe did not execute")
print("R437 PHYSICAL READONLY OBSERVER", "PARTIAL_ADDRESS_FIELD_TAG_PTR" if observation_ok else "INCOMPLETE_OR_UNSUPPORTED")
print("R437 OLD REPLACED COPY return: still requires independent native old-carrier observation")
print("R437 RESULT: NO_COMPLETE_PHYSICAL_NATIVE_WITNESS (must not report PASS)",flush=True)
