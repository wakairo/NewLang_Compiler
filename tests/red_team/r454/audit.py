#!/usr/bin/env python3
"""ONE finite independent R454 run. Fail closed on any source/profile/proof/native gap."""
import hashlib
import os
import pathlib
import platform
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "output"
OUT.mkdir(exist_ok=True)
BIN = ROOT / "build-r454" / "newlangc"
BASE = "d26d30568018f9d4866a9841d9eba6966a703557"
class Halt(Exception):
    pass
def sha(b):
    return hashlib.sha256(b).hexdigest()
def run(args, expected=0, env=None):
    p = subprocess.run([str(x) for x in args], cwd=ROOT,
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env)
    print("COMMAND", " ".join(map(str,args)), "EXIT", p.returncode, flush=True)
    if p.stderr:
        print("STDERR",p.stderr.decode(errors="replace")[:6000],flush=True)
    if expected is not None and p.returncode != expected:
        raise Halt("unexpected exit, expected %s: %s" % (expected, args))
    return p
def check_output(p, needle):
    if needle not in p.stderr.decode(errors="replace"):
        raise Halt("missing runtime witness: "+needle)
def compiler(cc):
    name=shutil.which(cc)
    if not name:
        raise Halt("missing compiler: "+cc)
    return name
def main():
    print("R454 CALIBRATED START",platform.platform(),"GITHUB_SHA",os.getenv("GITHUB_SHA"),
          "RUN_ID",os.getenv("GITHUB_RUN_ID"),"ATTEMPT",os.getenv("GITHUB_RUN_ATTEMPT"),flush=True)
    got=run(["git","rev-parse","HEAD"]).stdout.decode().strip()
    if got != os.getenv("GITHUB_SHA"):
        raise Halt("checkout does not equal github SHA")
    run(["git","merge-base","--is-ancestor",BASE,"HEAD"])
    if os.getenv("GITHUB_RUN_ATTEMPT") != "1":
        raise Halt("forbidden rerun attempt")
    native_cases=[("none",HERE/"r_none.nl",0),("some",HERE/"r_some.nl",1)]
    produced={}
    for label,source,case_some in native_cases:
        body=source.read_bytes()
        print("R454 SOURCE",label,"bytes",len(body),"sha256",sha(body),flush=True)
        src=body.decode("utf-8")
        if src.count("next: Option<ptr<Node>>::None")!=2 or "next: Option<ptr<Node>>::Some" in src:
            raise Halt("initial None-only source profile invariant violated")
        p=run([BIN,"--check",source])
        if p.stdout or p.stderr:
            raise Halt("--check exit0 must be silent")
        print("R454 SOURCE CHECKED",label,flush=True)
        p=run([OUT/"public_proof",source])
        check_output(p,"R454 VALIDATED issued/copied")
        check_output(p,"R454 PUBLIC MUTATIONS refused=9 attempted=9")
        c=OUT/(label+".c")
        generated=run([BIN,source]).stdout
        if not generated:
            raise Halt("CLI4/C0 or empty C17")
        c.write_bytes(generated)
        print("R454 RAW GENERATED C17",label,"bytes",len(generated),"sha256",sha(generated),flush=True)
        t=generated.decode("utf-8")
        if len(re.findall(r"switch \(nl_v_\d+\.tag\) \{",t)) != 1 or not re.search(r"case 0: \{",t) or not re.search(r"case 1: \{",t):
            raise Halt("both real runtime normal arms not emitted")
        if "NL_NODE_FINISH();" not in t or t.count("NL_NODE_REPLACE(") < (2 if case_some else 1):
            raise Halt("required real physical event sites missing")
        produced[label]=c
        for cc,opt,flags in [
            ("gcc","o0",["-O0"]),("gcc","o2",["-O2"]),
            ("clang","o0",["-O0"]),("clang","o2",["-O2"]),
            ("clang","asan",["-O1","-fsanitize=address","-fno-omit-frame-pointer"]),
            ("clang","ubsan",["-O1","-fsanitize=undefined","-fno-sanitize-recover=all"]),
        ]:
            ex=OUT/(label+"-"+cc+"-"+opt)
            strict=["-std=c17","-Wall","-Wextra","-Wpedantic","-Werror"]
            run([compiler(cc),*strict,*flags,c,"-o",ex])
            env=os.environ.copy()
            env["ASAN_OPTIONS"]="detect_leaks=1:halt_on_error=1"
            env["UBSAN_OPTIONS"]="halt_on_error=1:print_stacktrace=1"
            run([ex],env=env)
            # Exactly the same source-generated bytes, compiled with a const-only
            # observer include. No mutation or re-emission of successful guest C.
            obs=OUT/(label+"-"+cc+"-"+opt+"-observed")
            define='-DNEWLANG_NODE_OBSERVER="tests/red_team/r454/observer.h"'
            run([compiler(cc),*strict,*flags,"-I.",define,"-DR454_CASE_SOME="+str(case_some),c,"-o",obs])
            p=run([obs],env=env)
            check_output(p,"R454_NATIVE_OBSERVER_OK case="+label)
            if c.read_bytes()!=generated:
                raise Halt("observer build modified pristine generated C17")
            print("R454 PAIR VERIFIED",label,cc,opt,"raw_C_sha",sha(generated),
                  "native_sha",sha(ex.read_bytes()),"observed_sha",sha(obs.read_bytes()),flush=True)
        # A corruption to C made separately AFTER hashing pristine generated C.
        # It does not claim the mutated file was source-checked or emitter-issued.
        mutation=t.replace("NL_NODE_FINISH();",
                           "((nl_node *)(void *)r454_anchor)->f1 ^= 1U;\nNL_NODE_FINISH();",1)
        if mutation==t: raise Halt("negative observer falsifier missing insertion point")
        bad=OUT/(label+"-corrupt-sibling.c")
        bad.write_text(mutation)
        print("R454 MUTATED C NEGATIVE",label,sha(bad.read_bytes()),flush=True)
        exe=OUT/(label+"-corrupt-sibling")
        run([compiler("gcc"),"-std=c17","-Wall","-Wextra","-Wpedantic","-Werror","-O0",
            "-I.",'-DNEWLANG_NODE_OBSERVER="tests/red_team/r454/observer.h"',
            "-DR454_CASE_SOME="+str(case_some),bad,"-o",exe])
        p=run([exe],expected=None)
        if p.returncode==0 or "R454_OBSERVER_REFUSED" not in p.stderr.decode(errors="replace"):
            raise Halt("separate corrupted-C falsifier not refused")
        print("R454 CORRUPTED C REFUSED",label,p.returncode,flush=True)
    original=(HERE/"r_none.nl").read_text()
    invalids={
      "wrong_field":original.replace("anchor@next","anchor@payload"),
      "escaped_ref":original.replace("replace(w, Option<ptr<Node>>::Some(peer_ptr))","w"),
    }
    for label,s in invalids.items():
        if s==original: raise Halt("failed to construct source-invalid negative "+label)
        path=OUT/(label+".nl");path.write_text(s)
        print("R454 SOURCE NEGATIVE",label,sha(path.read_bytes()),flush=True)
        p=run([BIN,"--check",path],expected=3)
        if p.stdout: raise Halt("rejected source emitted C")
        print("R454 SOURCE REJECTED",label,flush=True)
    print("R454 CALIBRATED: PASS TESTED FINITE PROFILE (LLVM-free partial integration only)",flush=True)
if __name__=="__main__":
    try: main()
    except Halt as e:
        print("R454 STOP FINDING/BLOCKED/ENVIRONMENT: ",str(e),flush=True)
        sys.exit(1)
