"""T993 strict declarative CTest enrollment; no evaluation of untrusted CMake."""
import hashlib
import pathlib
import re
import sys

HEADER = "NL_R_COHORT_V1"
NAME = re.compile(r"r([1-9][0-9]{2,5})_([a-z][a-z0-9_]{1,39})\Z", re.ASCII)
SHA = re.compile(r"[0-9a-f]{64}\Z", re.ASCII)
FILE = re.compile(r"tests/(?:r[1-9][0-9]{2,5}|t993)/sources/[A-Za-z][A-Za-z0-9_]{0,63}\.nl\Z", re.ASCII)
MODES = {"check_accept", "check_reject"}
MAX_MANIFEST = 4096
MAX_SOURCE = 65536
MAX_CASES = 6


def reject(why):
    raise ValueError("T993 manifest STOP: " + why)


def safe_regular_file(root, rel):
    parts = pathlib.PurePosixPath(rel).parts
    if not parts or any(part in ("..", ".", "") for part in parts):
        reject("unsafe path")
    p = root
    for part in parts:
        p = p / part
        if p.is_symlink():
            reject("symlink path component")
    if not p.is_file():
        reject("source missing/not regular file")
    if not p.resolve().is_relative_to(root.resolve()):
        reject("path escapes source root")
    data = p.read_bytes()
    if len(data) > MAX_SOURCE:
        reject("oversized source")
    return data


def entries(root, manifest):
    root = pathlib.Path(root).absolute()
    manifest = pathlib.Path(manifest).absolute()
    allowed = (
        root / "tests/r/approved-cohort-manifest.txt",
        root / "tests/t993/approved-cohort-manifest.txt",
    )
    if manifest not in allowed:
        reject("manifest outside fixed allowlist")
    current = root
    for component in manifest.relative_to(root).parts:
        current = current / component
        if current.is_symlink():
            reject("symlink manifest path component")
    if not manifest.is_file() or not manifest.resolve().is_relative_to(root.resolve()):
        reject("manifest missing/nonregular/outside root")
    raw = manifest.read_bytes()
    if not (0 < len(raw) <= MAX_MANIFEST):
        reject("manifest empty or oversized")
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError:
        reject("manifest must be ASCII")
    if "\r" in text or "\x00" in text or not text.endswith("\n"):
        reject("manifest must use complete LF-only ASCII lines")
    lines = text.splitlines()
    if not lines or lines[0] != HEADER or not 1 <= len(lines) - 1 <= MAX_CASES:
        reject("header or case count")
    parsed = []
    seen_names, seen_sources = set(), set()
    cohort = None
    pilot = manifest == allowed[1]
    for line in lines[1:]:
        fields = line.split("|")
        if len(fields) != 4:
            reject("invalid column count or command")
        case, mode, source, expect_sha = fields
        name_match = NAME.fullmatch(case)
        if not name_match or mode not in MODES or not FILE.fullmatch(source) or not SHA.fullmatch(expect_sha):
            reject("invalid name, mode, source path, or checksum syntax")
        issue = name_match.group(1)
        if cohort is None:
            cohort = issue
        if issue != cohort:
            reject("mixed issue IDs")
        expected_prefix = "tests/t993/sources/" if pilot else f"tests/r{issue}/sources/"
        if (pilot and issue != "993") or not source.startswith(expected_prefix):
            reject("case ID/source namespace mismatch")
        name = case + ".integration"
        if name in seen_names or source in seen_sources:
            reject("duplicate test ID or source")
        seen_names.add(name)
        seen_sources.add(source)
        actual_sha = hashlib.sha256(safe_regular_file(root, source)).hexdigest()
        if actual_sha != expect_sha:
            reject("source SHA256 mismatch")
        parsed.append((name, mode, source, expect_sha))
    return parsed


def generate(root, manifest, output):
    parsed = entries(root, manifest)
    # Every interpolated character is restricted to a narrow verified ASCII alphabet.
    code = ["# T993 generated by trusted T-owned validator; NEVER include the R text manifest."]
    code.append('set(_t993_names "' + ";".join(x[0] for x in parsed) + '")')
    for name, mode, source, digest in parsed:
        code += [
            f"if(TEST {name})",
            f'    message(FATAL_ERROR "T993: duplicate registered CTest {name}")',
            "endif()",
            f"add_test(NAME {name} COMMAND \"${{Python3_EXECUTABLE}}\"",
            '    "${CMAKE_SOURCE_DIR}/cmake/independent-r-cohort-runner.py"',
            f'    "$<TARGET_FILE:newlangc>" "{mode}"',
            f'    "${{CMAKE_SOURCE_DIR}}/{source}" "{digest}")',
            f"set_tests_properties({name} PROPERTIES TIMEOUT 90",
            '    ENVIRONMENT "PYTHONDONTWRITEBYTECODE=1;PYTHONHASHSEED=0;LC_ALL=C;ASAN_OPTIONS=detect_leaks=1:halt_on_error=1;UBSAN_OPTIONS=halt_on_error=1:print_stacktrace=1")',
        ]
    path = pathlib.Path(output)
    if path.is_symlink() or not path.parent.is_dir():
        reject("unsafe generated output")
    path.write_text("\n".join(code) + "\n", encoding="ascii")
    return parsed


def main(argv):
    if len(argv) not in (3, 4):
        reject("expected: root manifest [trusted-output]")
    parsed = generate(*argv) if len(argv) == 3 else entries(*argv)
    print(f"T993 declarative validation PASS cases={len(parsed)}")


if __name__ == "__main__":
    try:
        main(sys.argv[1:])
    except (ValueError, OSError) as exc:
        print(f"T993 manifest rejected: {exc}", file=sys.stderr)
        sys.exit(2)
